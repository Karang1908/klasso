import puppeteer from "puppeteer-core";
import { mkdirSync } from "node:fs";

const out = ".impeccable/qa/planning";
mkdirSync(out, { recursive: true });
const browser = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
let passed = 0, failed = 0;
const check = (label, okay, detail = "") => { okay ? passed++ : failed++; console.log(`${okay ? "PASS" : "FAIL"}  ${label}${okay ? "" : ` — ${detail}`}`); };
const pause = (ms = 220) => new Promise((resolve) => setTimeout(resolve, ms));
const go = async (screen) => { await page.goto(`http://localhost:3000/preview?s=${screen}`, { waitUntil: "networkidle0" }); await pause(); };
const click = async (selector) => { await page.$eval(selector, (el) => el.scrollIntoView({ block: "center" })); await page.locator(selector).click(); await pause(); };
const textClick = async (text, selector = "button") => {
  const node = (await page.evaluateHandle((text, selector) => [...document.querySelectorAll(selector)].find((el) => el.textContent.trim() === text && el.getBoundingClientRect().height > 0), text, selector)).asElement();
  if (!node) throw new Error(`Missing control ${text}`);
  await node.evaluate((el) => el.scrollIntoView({ block: "center" })); await node.click(); await pause();
};
const type = async (selector, value) => { await page.$eval(selector, (el, value) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set.call(el, value); el.dispatchEvent(new Event("input", { bubbles: true })); }, value); await pause(); };
const chooseTime = async (label, time) => {
  await click(`input[aria-label="${label}"]`);
  await type('input[aria-label="Enter time HH:MM"]', time);
  await textClick("Apply", ".temporal-popup button");
};
const geometry = () => page.evaluate(() => {
  const panel = document.querySelector(".sheet-panel"), footer = document.querySelector(".sheet-footer"), body = document.querySelector(".sheet-body");
  const p = panel?.getBoundingClientRect(), f = footer?.getBoundingClientRect();
  return { padding: footer ? parseFloat(getComputedStyle(footer).paddingBottom) : 0, fit: Boolean(p && f && p.left >= 0 && p.right <= innerWidth + 1 && p.bottom <= innerHeight + 1 && f.bottom <= p.bottom + 1), scroll: body ? getComputedStyle(body).overflowY : "" };
});
try {
  await page.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true });
  await page.emulateMediaFeatures([{ name: "prefers-reduced-motion", value: "no-preference" }]);
  await go("planning");
  check("planning shows real classes alongside plans", await page.$$eval('.agenda-row[data-kind="class"]', (rows) => rows.length === 4));
  await textClick("A meeting");
  check("meeting is selected by the quick action", Boolean(await page.$('[aria-label="Plan type"] [aria-pressed="true"]')) && await page.$eval('[aria-label="Plan type"] [aria-pressed="true"]', (el) => el.textContent.includes("Meeting")));
  check("blank plan cannot save", await page.$eval('.sheet-footer button[type="submit"]', (button) => button.disabled));
  await type('[aria-label="Plan title"]', "UI project meeting");
  await type('[aria-label="Meeting participants"]', "Alex and Jamie");
  await type('[aria-label="Plan location"]', "Library room 2");
  await chooseTime("Plan start time", "14:00");
  await chooseTime("Plan end time", "13:00");
  check("invalid plan time cannot save", await page.$eval('.sheet-footer button[type="submit"]', (button) => button.disabled));
  await chooseTime("Plan end time", "15:00");
  check("valid time enables saving", !(await page.$eval('.sheet-footer button[type="submit"]', (button) => button.disabled)));
  await click('[aria-label="Plan subject"]');
  const menu = await page.$eval('.dropdown-popup', (el) => { const r = el.getBoundingClientRect(); return { top: r.top, bottom: r.bottom, right: r.right, popover: el.matches(":popover-open") }; });
  check("dropdown is in the top layer and inside viewport", menu.popover && menu.top >= 0 && menu.bottom <= 844 && menu.right <= 390, JSON.stringify(menu));
  check("dropdown has unique option IDs", await page.$$eval('[role="option"]', (els) => new Set(els.map((el) => el.id)).size === els.length));
  await page.keyboard.press("End");
  check("keyboard updates the active option", await page.$eval('[aria-label="Plan subject"][role="combobox"]', (el) => Boolean(document.getElementById(el.getAttribute("aria-activedescendant")))));
  await page.keyboard.press("Escape"); await pause();
  check("Escape dismisses dropdown without closing editor", !(await page.$(".dropdown-popup")) && Boolean(await page.$("dialog[open]")));
  await click('[aria-label="Plan subject"]'); await page.keyboard.press("ArrowDown"); await page.keyboard.press("Enter"); await pause();
  check("keyboard selection commits and restores trigger focus", await page.$eval('[aria-label="Plan subject"]', (el) => el === document.activeElement && el.getAttribute("aria-expanded") === "false"));
  const geo = await geometry();
  check("phone sheet has bottom breathing room", geo.fit && geo.padding >= 20 && geo.scroll === "auto", JSON.stringify(geo));
  await textClick("Add to plan", ".sheet-footer button");
  check("meeting saves to the agenda", Boolean(await page.$('[aria-label="Edit plan UI project meeting"]')));
  await page.reload({ waitUntil: "networkidle0" }); await pause();
  check("meeting survives preview reload", Boolean(await page.$('[aria-label="Edit plan UI project meeting"]')));
  await click('[aria-label="Edit plan UI project meeting"]');
  check("meeting details survive editing", await page.$eval('[aria-label="Meeting participants"]', (el) => el.value === "Alex and Jamie") && await page.$eval('[aria-label="Plan location"]', (el) => el.value === "Library room 2"));
  await click('[aria-label="Plan date"]');
  check("date picker is app-rendered", Boolean(await page.$('.temporal-popup:popover-open .picker-calendar')));
  await textClick("Done", ".temporal-popup button");
  await click('.sheet-close');
  await textClick("An activity"); await type('[aria-label="Plan title"]', "UI gym session");
  await click('.sheet-close');
  check("unsaved plan asks before discard", await page.$eval('.sheet-body', (el) => el.textContent.includes("discard your unsaved changes")));
  await textClick("Keep editing"); await textClick("Add to plan", ".sheet-footer button");
  check("activity saves without requiring a subject or time", Boolean(await page.$('[aria-label="Edit plan UI gym session"]')));
  await click('[aria-label="Mark UI gym session done"]');
  check("activity completion is visible", Boolean(await page.$('[aria-label="Mark UI gym session not done"]')));
  await go("calendar"); await click('main [aria-current="date"]');
  check("calendar day includes meetings and activities", await page.$eval('.sheet-body', (el) => el.textContent.includes("UI project meeting") && el.textContent.includes("UI gym session")));
  await click('[aria-label="Edit plan UI project meeting"]');
  check("calendar opens the same plan editor", Boolean(await page.$('[aria-label="Meeting participants"]')));
  await textClick("Delete", ".sheet-footer button");
  check("plan deletion asks for confirmation", await page.$eval('.sheet-body', (el) => el.textContent.includes("cannot be undone")));
  await textClick("Delete plan", ".sheet-body button");
  await go("planning");
  check("deleted meeting is removed everywhere", !(await page.$('[aria-label="Edit plan UI project meeting"]')));
  await go("timetable"); await textClick("Meeting");
  check("timetable can schedule a meeting", Boolean(await page.$('[aria-label="Meeting participants"]')));
  await click('.sheet-close');
  await go("planning&new=activity");
  await type('[aria-label="Plan title"]', "A very long activity title with enough detail to wrap across several lines without clipping or hiding the action controls");
  for (const size of [{ width: 320, height: 640 }, { width: 390, height: 420 }, { width: 768, height: 700 }, { width: 1440, height: 900 }]) {
    await page.setViewport(size); await pause(300);
    const result = await geometry();
    check(`editor fits ${size.width}×${size.height}`, result.fit && result.padding >= 20, JSON.stringify(result));
    check(`editor content is not horizontally clipped at ${size.width}`, await page.$eval('.sheet-body', (el) => el.scrollWidth <= el.clientWidth + 1));
  }
  await page.evaluate(() => { document.documentElement.style.fontSize = "200%"; }); await pause(300);
  check("sheet survives doubled text", (await geometry()).fit && await page.$eval('.sheet-body', (el) => el.scrollWidth <= el.clientWidth + 1));
  await page.evaluate(() => { document.documentElement.style.fontSize = ""; });
  await go("loading");
  check("loading screen uses the same animated logo", Boolean(await page.$('.brandmark-loading .bm-arc')) && await page.$eval('.launch', (el) => el.getAttribute("aria-busy") === "true"));
  await page.emulateMediaFeatures([{ name: "prefers-reduced-motion", value: "reduce" }]);
  check("reduced motion leaves logo visible", await page.$eval('.bm-arc', (el) => getComputedStyle(el).opacity !== "0"));
  await go("today");
  check("no OS dropdowns, date or time controls remain", await page.$$eval('select, input[type="date"], input[type="time"]', (els) => els.length === 0));
  check("no uncaught browser errors", errors.length === 0, errors.join(" | "));
} catch (error) { failed++; console.error("FAIL  planning sequence", error); }
finally { await browser.close(); }
console.log(`\n${passed} passed; ${failed} failed.`);
process.exitCode = failed ? 1 : 0;
